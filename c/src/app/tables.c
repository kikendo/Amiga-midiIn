double tonetable(LONG i)
{
	union {
		ULONG l[2];
		double d;
	} u;

	if (i < 0)
		i = 0;
	if (i >= TONETABLE_LEN)
		i = TONETABLE_LEN - 1;
	u.l[0] = tonetable_raw[2 * i];
	u.l[1] = tonetable_raw[2 * i + 1];
	return u.d;
}

