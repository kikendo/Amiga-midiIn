void locale_open(void)
{
	LocaleBase = (struct LocaleBase *)OpenLibrary((CONST_STRPTR)"locale.library", 0);
	if (LocaleBase)
		catalog = OpenCatalogA(0, (CONST_STRPTR)"midiIn.catalog", 0);
}

void locale_close(void)
{
	if (LocaleBase) {
		CloseCatalog(catalog);
		catalog = 0;
		CloseLibrary((struct Library *)LocaleBase);
		LocaleBase = 0;
	}
}

STRPTR getLocStr(LONG id, LONG *gadchar)
{
	STRPTR ret;
	LONG i;

	if (id == STRID_MIDIIN)
		return (STRPTR)strings[id];
	if (id < 0 || id >= STRID_MAX)
		return (STRPTR)"";
	ret = (STRPTR)strings[id];
	if (LocaleBase)
		ret = (STRPTR)GetCatalogStr(catalog, id, (CONST_STRPTR)strings[id]);
	if (ret[0] && ret[1] == 0 && gadchar != LOC_KEYS) {
		ret += 2;
	} else if (gadchar == LOC_KEYS && !(ret[0] && ret[1] == 0)) {
		ret = 0;
	} else if (gadchar && gadchar != LOC_KEYS) {
		for (i = 0; ret[i] && ret[i] != '_'; i++)
			;
		*gadchar = ret[i] ? (LONG)ToLower((ULONG)(UBYTE)ret[i + 1]) : 0;
	}
	return ret;
}
